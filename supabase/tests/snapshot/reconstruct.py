"""Reviewed public metadata reconstruction; never connects to a remote database.

Auth schema comes from local GoTrue migrations (or a minimal FK stub in pure PG).
Sequence max in supplied JSON lost int64 precision; local default is deliberately
not claimed as an exact reconstruction of that option. No DML grants are added.
"""
import json
from pathlib import Path
ROWS=json.loads((Path(__file__).parent/'real_definitions.json').read_text())
def group(section): return [r for r in ROWS if r['section']==section]
def ident(s): return '"'+s.replace('"','""')+'"'
def presented(s): return s.replace('\\n','\n').replace('\\r','\r')
def reconstruct(sql,db):
    commands=['SET search_path=public;']
    for t in group('01_tables'):
        assert t['details']=={'rls':True,'owner':'postgres','force_rls':False}
        cols=[]
        for c in group('02_columns'):
            table,col=c['name'].split('.',1); d=c['details']
            if table!=t['name']:continue
            assert not d['generated']
            suffix=' GENERATED BY DEFAULT AS IDENTITY' if d['identity']=='d' else ''
            assert d['identity'] in ('','d')
            if d['default'] is not None:suffix+=' DEFAULT '+d['default']
            if d['not_null']:suffix+=' NOT NULL'
            cols.append(ident(col)+' '+d['type']+suffix)
        commands.append('CREATE TABLE public.'+ident(t['name'])+' ('+','.join(cols)+');')
        commands.append('ALTER TABLE public.'+ident(t['name'])+' ENABLE ROW LEVEL SECURITY;')
    for c in sorted(group('04_constraints'),key=lambda c:c['details']['type']=='f'):
        t,n=c['name'].split('.',1);d=c['details']
        assert d['validated'] and not d['deferrable'] and not d['initially_deferred']
        commands.append(f'ALTER TABLE public.{ident(t)} ADD CONSTRAINT {ident(n)} {d["definition"]};')
    constraint_names={c['name'] for c in group('04_constraints')}
    for i in group('05_indexes'):
        assert i['details']['valid']
        if i['name'] not in constraint_names:commands.append(i['details']['definition']+';')
    for f in group('06_helpers'):
        assert f['details']['owner']=='postgres'
        assert f['details']['acl']==['=X/postgres','postgres=X/postgres','authenticated=X/postgres']
        commands.append(presented(f['details']['definition'])+';')
        commands.append('GRANT EXECUTE ON FUNCTION public.'+f['name']+' TO authenticated;')
    for p in group('03_policies'):
        t,n=p['name'].split('.',1);d=p['details']
        role=','.join('PUBLIC' if r=='public' else ident(r) for r in d['roles'])
        command={'r':'SELECT','a':'INSERT','w':'UPDATE','d':'DELETE','*':'ALL'}[d['command']]
        stmt=f'CREATE POLICY {ident(n)} ON public.{ident(t)} AS '+('PERMISSIVE' if d['permissive'] else 'RESTRICTIVE')+f' FOR {command} TO {role}'
        if d['using']:stmt+=' USING ('+presented(d['using'])+')'
        if d['with_check']:stmt+=' WITH CHECK ('+presented(d['with_check'])+')'
        commands.append(stmt+';')
    for g in group('07_table_grants'):
        d=g['details'];assert d['grantor']=='postgres' and not d['grant_option']
        assert d['privilege'] in {'SELECT','INSERT','UPDATE','DELETE','TRUNCATE','TRIGGER','REFERENCES','MAINTAIN'}
        commands.append(f'GRANT {d["privilege"]} ON public.{ident(g["name"])} TO {ident(d["grantee"])};')
    for g in group('08_default_grants'):
        schema,creator=g['name'].split('.',1);d=g['details'];assert schema=='public' and d['grantor']==creator
        kind={'r':'TABLES','S':'SEQUENCES','f':'FUNCTIONS'}[d['object_type']]
        commands.append(f'ALTER DEFAULT PRIVILEGES FOR ROLE {ident(creator)} IN SCHEMA public GRANT {d["privilege"]} ON {kind} TO {ident(d["grantee"])}'+(' WITH GRANT OPTION' if d['grant_option'] else '')+';')
    sql('\n'.join(commands),db)

def seed(sql,db,uid):
    for org in [1,2]:sql(f"INSERT INTO organizations(id,name) VALUES ('{uid(org)}','Fictitious {org}');",db)
    for unit,org in [(11,1),(12,1),(21,2),(22,2)]:
        sql(f"INSERT INTO units(id,organization_id,name) VALUES ('{uid(unit)}','{uid(org)}','Synthetic {unit}');",db)
    for table,items in [('machines',[(101,11),(102,12),(121,21)]),('devices',[(301,11),(302,12),(321,21)]),('reservoirs',[(401,11),(402,12),(421,21)])]:
        for n,unit in items:sql(f"INSERT INTO {table}(id,unit_id,name) VALUES ('{uid(n)}','{uid(unit)}','Synthetic {n}');",db)
